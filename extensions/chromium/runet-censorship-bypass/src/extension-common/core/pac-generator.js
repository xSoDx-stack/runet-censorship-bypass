/**
 * Generate a standalone, production-ready FindProxyForURL PAC script
 * @param {Object} options
 * @returns {string} Generated JavaScript PAC script
 */
export function generatePacScript({
  domains = [],
  proxies = '',
  proxyString = '',
  fallback = 'DIRECT',
  bypassLocal = true,
  ifProxyOrDie = false,
  ifProxyHttpsOnly = false,
  ifProhibitDns = false,
} = {}) {
  const cleanDomains = parseDomainsInput(domains);
  
  let effectiveProxy = (proxyString || proxies || 'HTTPS proxy.antizapret.prostovpn.org:8443; PROXY proxy.antizapret.prostovpn.org:8443; DIRECT').trim();
  if (!effectiveProxy) {
    effectiveProxy = 'DIRECT';
  }

  // Format fallback routing
  const fallbackStr = ifProxyOrDie ? '' : (fallback || 'DIRECT');

  // Build dictionary of domains for O(1) hash lookups
  const exactMap = {};
  for (const d of cleanDomains) {
    exactMap[d] = 1;
  }

  const domainsJson = JSON.stringify(exactMap, null, 0);
  const timestamp = new Date().toLocaleString('ru-RU');

  const script = `/**
 * Generated by AntiCheburnet Local PAC Generator
 * Timestamp: ${timestamp}
 * Rules count: ${cleanDomains.length} domains
 * Mode: Local CWS-Compliant PAC Engine
 */
;(function(global) {
  "use strict";

  var PROXY_ROUTE = ${JSON.stringify(effectiveProxy)};
  var FALLBACK_ROUTE = ${ifProxyOrDie ? '""' : JSON.stringify(fallbackStr)};
  var IF_PROXY_HTTPS_ONLY = ${Boolean(ifProxyHttpsOnly)};
  var IF_PROHIBIT_DNS = ${Boolean(ifProhibitDns)};
  var IF_PROXY_OR_DIE = ${Boolean(ifProxyOrDie)};

  // High-performance hash dictionary of domains
  var DOMAINS = ${domainsJson};

  function isLocalNetwork(host) {
    if (!host) return true;
    var h = host.toLowerCase();
    if (h === 'localhost' || h === '127.0.0.1' || h === '::1' || h === '0.0.0.0') return true;
    if (h.indexOf('.local') !== -1 || h.indexOf('.localhost') !== -1 || h.indexOf('.internal') !== -1) return true;
    if (/^10\\./.test(h) || /^192\\.168\\./.test(h) || /^172\\.(1[6-9]|2[0-9]|3[0-1])\\./.test(h)) return true;
    return false;
  }

  function isDomainBlocked(host) {
    if (!host) return false;
    var h = host.toLowerCase();
    
    // 1. Direct match (e.g. rutracker.org)
    if (DOMAINS[h] === 1) return true;

    // 2. Subdomain / suffix match (e.g. static.rutracker.org -> rutracker.org)
    var dot = h.indexOf('.');
    while (dot !== -1) {
      h = h.slice(dot + 1);
      if (DOMAINS[h] === 1) return true;
      dot = h.indexOf('.');
    }

    return false;
  }

  function FindProxyForURL(url, host) {
    if (!host) return "DIRECT";

    ${bypassLocal ? `// 1. Bypass local / intranet resources
    if (isLocalNetwork(host) || isPlainHostName(host)) {
      return "DIRECT";
    }
` : ''}
    ${ifProxyHttpsOnly ? `// 2. HTTPS-only filter
    if (url && url.indexOf('https:') !== 0) {
      return "DIRECT";
    }
` : ''}
    // 3. Fast O(1) check against blocked domains dictionary
    if (isDomainBlocked(host)) {
      return PROXY_ROUTE;
    }

    // 4. Default unblocked traffic
    return FALLBACK_ROUTE;
  }

  if (typeof global !== 'undefined') {
    global.FindProxyForURL = FindProxyForURL;
  }
  if (typeof self !== 'undefined') {
    self.FindProxyForURL = FindProxyForURL;
  }
})(this);
`;

  return script;
}

/**
 * Sandboxed live tester for generated PAC scripts
 * @param {string} pacScriptCode 
 * @param {string} testUrl 
 * @returns {Object} Test result object
 */
export function testPacRule(pacScriptCode, testUrl) {
  if (!pacScriptCode || !testUrl) {
    return { success: false, error: 'Укажите URL или домен для проверки' };
  }

  try {
    let cleanUrl = String(testUrl).trim();
    if (!cleanUrl.includes('://')) {
      cleanUrl = 'https://' + cleanUrl;
    }

    let parsedHost = '';
    try {
      const u = new URL(cleanUrl);
      parsedHost = u.hostname;
    } catch {
      parsedHost = cleanUrl.replace(/^[a-z]+:\/\//i, '').split('/')[0].split(':')[0];
    }

    // Mock browser PAC runtime global functions
    const sandboxGlobal = {
      isPlainHostName: (h) => !h.includes('.'),
      dnsDomainIs: (h, d) => h === d || h.endsWith('.' + d),
      shExpMatch: (str, pat) => {
        try {
          const regex = new RegExp('^' + pat.replace(/\./g, '\\.').replace(/\*/g, '.*').replace(/\?/g, '.') + '$', 'i');
          return regex.test(str);
        } catch {
          return false;
        }
      },
      isInNet: () => false,
      dnsResolve: () => null,
      myIpAddress: () => '127.0.0.1',
      FindProxyForURL: null,
    };

    const runner = new Function(
      'global',
      'isPlainHostName',
      'dnsDomainIs',
      'shExpMatch',
      'isInNet',
      'dnsResolve',
      'myIpAddress',
      pacScriptCode + '\nreturn (typeof FindProxyForURL === "function" ? FindProxyForURL : global.FindProxyForURL);'
    );

    const findProxyFn = runner(
      sandboxGlobal,
      sandboxGlobal.isPlainHostName,
      sandboxGlobal.dnsDomainIs,
      sandboxGlobal.shExpMatch,
      sandboxGlobal.isInNet,
      sandboxGlobal.dnsResolve,
      sandboxGlobal.myIpAddress
    );

    if (typeof findProxyFn !== 'function') {
      return { success: false, error: 'Функция FindProxyForURL не найдена в PAC-скрипте' };
    }

    const startTime = performance.now();
    const route = findProxyFn(cleanUrl, parsedHost) || '';
    const executionTimeMs = (performance.now() - startTime).toFixed(3);
    const isProxied = Boolean(route && !route.trim().startsWith('DIRECT'));

    return {
      success: true,
      url: cleanUrl,
      host: parsedHost,
      route,
      isProxied,
      executionTimeMs,
    };
  } catch (err) {
    return {
      success: false,
      error: err.message || String(err),
    };
  }
}
