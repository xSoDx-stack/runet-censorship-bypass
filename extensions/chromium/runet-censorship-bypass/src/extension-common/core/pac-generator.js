/**
 * Parse and clean input domain lists from text/file/raw data
 * @param {string|string[]} input 
 * @returns {string[]} Clean sorted array of unique domains
 */
export function parseDomainsInput(input) {
  if (!input) return [];
  const lines = Array.isArray(input) ? input : String(input).split(/[\r\n,;]+/);
  const domains = new Set();

  for (let line of lines) {
    if (!line) continue;
    let d = String(line).trim().toLowerCase();
    
    // Remove comments
    d = d.replace(/#.*$/, '').replace(/\/\/.*$/, '').trim();
    if (!d) continue;

    // Strip URL parts if full URL is passed
    d = d.replace(/^[a-z]+:\/\//i, '');
    d = d.split('/')[0];
    d = d.split(':')[0];
    d = d.trim();

    // Strip leading wildcard or dots (*.domain.com -> domain.com)
    d = d.replace(/^\*\.?/, '').replace(/^\.+/, '').trim();
    
    // Validate domain format (at least something.something or valid hostname)
    if (d && (d.includes('.') || d === 'localhost') && !/\s/.test(d)) {
      domains.add(d);
    }
  }

  return Array.from(domains).sort();
}

